package com.training.cicdpipeline;

public class CiAndCdPipeLine {
    public static void main(String[] args) {
        /**
         * ✅ CI/CD means:
         * CI = Continuous Integration
         * CD = Continuous Deployment (or Delivery)
         *
         * Think of it like:
         *      “You just push the code, and automation handles the rest.”
         *
         * Term	Meaning
         * CI (Continuous Integration)	Whenever you push code, it’s automatically tested & built
         * CD (Continuous Deployment/Delivery)	Your code is automatically deployed (uploaded) to a server,
         *     a live website, or cloud
         *
         * 🧠 Why Use CI/CD?
         * ✅ Saves time
         * ✅ Reduces human error
         * ✅ Ensures code is tested
         * ✅ Automates build + deployment
         *
         *
         * 🛠️ Tools You Can Use
         *     Tool	Used For
         *     GitHub Actions	Best for GitHub-based projects
         *     GitLab CI	Comes built-in with GitLab
         *     Jenkins	Open-source, customizable
         *     CircleCI / Travis CI	Used by startups, open source
         *
         *
         * 🎯 Use of CI/CD Pipelines (in simple lines):
         * 🚀 Automatically builds and tests your code when you push it to Git.
         *
         * 🔎 Catches bugs early before going to production.
         *
         * ⚙️ Saves time by automating tasks like build, test, and deploy.
         *
         * 📦 Delivers code faster to production without manual steps.
         *
         * 🔄 Keeps your project up-to-date and working after every change.
         */
    }
}
