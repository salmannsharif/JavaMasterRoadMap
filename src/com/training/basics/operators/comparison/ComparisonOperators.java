package com.training.basics.operators.comparison;

public class ComparisonOperators {
    public void comparisonOperators(){
        int a = 10;
        int b = 20;
        System.out.println(a == b); // false
        System.out.println(a!= b); // true
        System.out.println(a > b); // false
        System.out.println(a < b); // true
        System.out.println(a >= b); // false
        System.out.println(a <= b); // true
    }
}
