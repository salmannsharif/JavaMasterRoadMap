package com.training.basics.operators.assignment;

public class AssignmentOperators {
    public void assignmentOperators(){
        int a = 10;
        a += 5;
        System.out.println(a);
        a -= 5;
        System.out.println(a);
        a *= 5;
        System.out.println(a);
        a /= 5;
        System.out.println(a);
        a %= 5;
        System.out.println(a);
    }
}
