package com.training.basics.control_statements.loopingStatements;

public class ForLoopStatement {
    public static void main(String[] args) {

        // Print numbers from 0 to 9 using for loop
        for (int i = 0; i < 10; i++) {
            System.out.println("Number: " + i);
        }

        // Print numbers from 10 to 1 using for loop
        for (int i = 10; i > 0; i--) {
            System.out.println("Number: " + i);
        }

        // Print numbers from 0 to 9 in reverse order using for loop
        for (int i = 9; i >= 0; i--) {
            System.out.println("Number: " + i);
        }

        // Print numbers from 10 to 1 in reverse order using for loop
        for (int i = 10; i > 0; i--) {
            System.out.println("Number: " + i);
        }

        // Print numbers from 1 to 10 in reverse order using for loop
        for (int i = 10; i >= 1; i--) {
            System.out.println("Number: " + i);
        }

    }
}
